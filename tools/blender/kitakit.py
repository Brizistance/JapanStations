def plant(p, x0, x1, y, z0, z1, seed=3):
    """Roof plant: a parapet, machine rooms, cooling towers, a tank, ducts."""
    r = random.Random(seed)
    for a, b_, c, d in ((x0, x1, z0, z0 + 0.3), (x0, x1, z1 - 0.3, z1), (x0, x0 + 0.3, z0, z1), (x1 - 0.3, x1, z0, z1)):
        p.box(CONC, a, y, c, b_, y + 1.1, d)
    w, d = x1 - x0, z1 - z0
    p.box(ROOF, x0 + w * 0.3, y, z0 + d * 0.35, x0 + w * 0.62, y + 4.2, z0 + d * 0.7)
    for _ in range(4):
        cx, cz = r.uniform(x0 + 3, x1 - 3), r.uniform(z0 + 3, z1 - 3)
        ww, dd, hh = r.uniform(2, 4.5), r.uniform(2, 4), r.uniform(1.4, 2.6)
        p.box(ACU, cx - ww / 2, y, cz - dd / 2, cx + ww / 2, y + hh, cz + dd / 2)
        p.box(DARK, cx - ww / 2 + 0.2, y + hh, cz - dd / 2 + 0.2, cx + ww / 2 - 0.2, y + hh + 0.05, cz + dd / 2 - 0.2)
    if w > 14 and d > 14:
        tank(p, x0 + w * 0.16, y, z0 + d * 0.2)


