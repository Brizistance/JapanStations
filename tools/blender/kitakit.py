# Shared helpers for the Kita-Ōdōri district's models (build_kitafront.py, build_mioya.py,
# build_gate.py, build_viaduct.py, build_ring.py, build_kitaarcade.py, build_kitacity.py).
#
# Frame and Part: see buildkit.py (front at z = 0 facing -z, origin mid-frontage on the pavement,
# +z into the plot). Wall faces are named as in build_plaza.py: 'f' front (z = at, facing -z),
# 'b' back (facing +z), 'l' the -x side, 'r' the +x side.
#
# Models carry no information. Where the game puts a name, a clock or a screen on a model, the
# script records the place with mark(); write_anchors() then writes src/stations/anchors/<kind>.ts,
# so the street code never mirrors a number by hand.

