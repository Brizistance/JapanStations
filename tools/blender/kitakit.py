def mast(p, x, y, z, h, w=2.2):
    """A red-and-white lattice aerial."""
    n = max(3, int(h / 5))
    for i in range(n):
        ya, yb = y + i * h / n, y + (i + 1) * h / n
        wa, wb = w * (1 - 0.8 * i / n), w * (1 - 0.8 * (i + 1) / n)
        col = RED if i % 2 == 0 else WHITE
        for sx in (-1, 1):
            for sz in (-1, 1):
                p.face(col, [(x + sx * wa / 2 - 0.07, ya, z + sz * wa / 2), (x + sx * wa / 2 + 0.07, ya, z + sz * wa / 2),
                             (x + sx * wb / 2 + 0.07, yb, z + sz * wb / 2), (x + sx * wb / 2 - 0.07, yb, z + sz * wb / 2)], (0, 0, sz))
                p.face(col, [(x + sx * wa / 2, ya, z + sz * wa / 2 - 0.07), (x + sx * wa / 2, ya, z + sz * wa / 2 + 0.07),
                             (x + sx * wb / 2, yb, z + sz * wb / 2 + 0.07), (x + sx * wb / 2, yb, z + sz * wb / 2 - 0.07)], (sx, 0, 0))
        p.box(col, x - wb / 2, yb - 0.08, z - wb / 2, x + wb / 2, yb, z + wb / 2)
    p.box(STEEL, x - 0.06, y + h, z - 0.06, x + 0.06, y + h + 4, z + 0.06)
    p.box(BEACON, x - 0.2, y + h + 4, z - 0.2, x + 0.2, y + h + 4.4, z + 0.2)


