NORMAL = {'f': (0, 0, -1), 'b': (0, 0, 1), 'l': (-1, 0, 0), 'r': (1, 0, 0)}


def wpt(face, a, y, at, t=0.0):
    """A point on a wall: a along it, y up, t metres in behind its plane."""
    if face == 'f':
        return (a, y, at + t)
    if face == 'b':
        return (a, y, at - t)
    if face == 'l':
        return (at + t, y, a)
    return (at - t, y, a)


def arch(p, mat, face, a0, a1, ys, yc, yt, at, thick, n=10, soffit=None, inner=True):
    """The wall over an arched opening a0 … a1: springing at ys, crown at yc, wall up to yt, `thick` deep."""
    c, R, rise = (a0 + a1) / 2, (a1 - a0) / 2, yc - ys
    yy = lambda a: ys + rise * math.sqrt(max(0.0, 1 - ((a - c) / R) ** 2))
    nrm = NORMAL[face]
    cx = wpt(face, c, ys - R, at, thick / 2)
    for k in range(n):
        xa, xb = a0 + (a1 - a0) * k / n, a0 + (a1 - a0) * (k + 1) / n
        ya, yb = yy(xa), yy(xb)
        p.face(mat, [wpt(face, xa, ya, at), wpt(face, xb, yb, at), wpt(face, xb, yt, at), wpt(face, xa, yt, at)], nrm)
        if inner:
            p.face(mat, [wpt(face, xa, ya, at, thick), wpt(face, xb, yb, at, thick), wpt(face, xb, yt, at, thick), wpt(face, xa, yt, at, thick)], tuple(-v for v in nrm))
        m = wpt(face, (xa + xb) / 2, (ya + yb) / 2, at, thick / 2)
        p.face(soffit or mat, [wpt(face, xa, ya, at), wpt(face, xb, yb, at), wpt(face, xb, yb, at, thick), wpt(face, xa, ya, at, thick)],
               (cx[0] - m[0], cx[1] - m[1], cx[2] - m[2]))


def wbox(p, mat, face, a0, a1, y0, y1, at, t0, t1):
    """A box given along a wall: from t0 to t1 metres behind its plane (negative: in front)."""
    q0, q1 = wpt(face, a0, y0, at, t0), wpt(face, a1, y1, at, t1)
    p.box(mat, q0[0], q0[1], q0[2], q1[0], q1[1], q1[2])


def pyramid(p, mat, x0, x1, z0, z1, y, h):
    cx, cz = (x0 + x1) / 2, (z0 + z1) / 2
    apex = (cx, y + h, cz)
    p.face(mat, [(x0, y, z0), (x1, y, z0), apex], (0, 0.5, -1))
    p.face(mat, [(x0, y, z1), (x1, y, z1), apex], (0, 0.5, 1))
    p.face(mat, [(x0, y, z0), (x0, y, z1), apex], (-1, 0.5, 0))
    p.face(mat, [(x1, y, z0), (x1, y, z1), apex], (1, 0.5, 0))


