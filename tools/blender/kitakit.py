def shopfronts(p, s, x0, x1, z, h, r, bay=5.2, door=None, awn=True):
    """Street storey of a commercial front: displays between piers, a fascia board over each, an awning or a lit soffit."""
    for c in rows(x0 + 0.4, x1 - 0.4, bay):
        if door is not None and abs(c - door) < bay * 0.55:
            continue
        display(p, c - bay / 2 + 0.35, c + bay / 2 - 0.35, 0.0, h - 1.2, z)
        fascia(s, c - bay / 2 + 0.3, c + bay / 2 - 0.3, h - 1.1, h - 0.15, z, r=r)
        if awn and r.random() < 0.5:
            col = r.choice(['#8f2020', '#12382c', '#1f3f7a', '#3a3d41', '#b35a1c'])
            p.prism('flat:' + col, [(z, h - 1.2), (z - 1.3, h - 1.75), (z - 1.3, h - 1.65), (z, h - 1.1)], 'x', c - bay / 2 + 0.3, c + bay / 2 - 0.3)
    if door is not None:
        p.box(GRANITE, door - bay * 0.5, 0, z - 0.3, door + bay * 0.5, h, z)
        doors(p, door, 0, z - 0.3, min(3.0, bay * 0.6), 2.8)
        p.box(ALU_DK, door - bay * 0.55, 3.2, z - 2.2, door + bay * 0.55, 3.4, z - 0.3)
        p.box('light', door - bay * 0.5, 3.16, z - 2.0, door + bay * 0.5, 3.2, z - 0.4)


